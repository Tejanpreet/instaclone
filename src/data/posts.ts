export const getPostById = (id: string): post | undefined  => {
  return posts.find((post) => post.id === id);
}

// A user's posts for their profile grid: pinned first, then newest first.
export const getPostsByUser =(userId:string) : post[] => {
   return posts
              .filter((post) => post.authorId === userId)
              .sort((a,b) => Number(b.isPinned ?? false)- Number(a.isPinned ?? false) || a.hoursAgo - b.hoursAgo);
}

export const getExplorePosts = (currentUserId: string):post[] => {
   return posts.filter((post) => post.authorId !== currentUserId && post.viewsCount !== undefined);
}